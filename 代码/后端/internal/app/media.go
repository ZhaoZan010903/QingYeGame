// Decoding is bounded independently from compressed upload size.
const maxImagePixels int64 = 16000000

// Upload sanitization and thumbnail generation share one decoder slot. A
// 16-bit PNG can use eight bytes per decoded pixel before codec work buffers.
var imageProcessors = make(chan struct{}, 1)

func (a *App) registerMedia(mux *http.ServeMux) {
	mux.HandleFunc("POST /api/v1/uploads", a.memberMutation(a.createUpload))
	mux.HandleFunc("PUT /api/v1/uploads/{id}/content", a.memberMutation(a.receiveUpload))
	mux.HandleFunc("POST /api/v1/uploads/{id}/complete", a.memberMutation(a.completeUpload))
	mux.HandleFunc("GET /api/v1/media/{id}", a.serveMedia)
	mux.HandleFunc("GET /api/v1/media/{id}/file", a.serveMedia)
	mux.HandleFunc("GET /api/v1/media/{id}/preview", a.serveMedia)
}
func (a *App) uploadMax() int64 {
	if a.Config.MaxUploadBytes > 0 {
		return a.Config.MaxUploadBytes
	}
	return 10 << 20
}
func validUploadName(name, mime string) bool {
	if name == "" || len(name) > 240 || strings.ContainsAny(name, "/\\\x00") {
		return false
	}
	ext := strings.ToLower(filepath.Ext(name))
	switch mime {
	case "image/jpeg":
		return ext == ".jpg" || ext == ".jpeg"
	case "image/png":
		return ext == ".png"
	case "image/webp":
		return ext == ".webp"
	}
	return false
}
func (a *App) createUpload(w http.ResponseWriter, r *http.Request) {
	u, ok := a.requireUser(w, r)
	if !ok {
		return
	}
	var input struct {
		Filename string `json:"filename"`
		MIME     string `json:"mime_type"`
		Size     int64  `json:"byte_size"`
	}
	if !readJSON(w, r, &input) {
		return
	}
	if input.Size <= 0 || input.Size > a.uploadMax() {
		fail(w, 413, "IMAGE_TOO_LARGE", "单张图片大小超过限制")
		return
	}
	if !validUploadName(input.Filename, input.MIME) {
		fail(w, 422, "INVALID_IMAGE_TYPE", "请选择扩展名与格式一致的 JPG、PNG 或 WebP 图片")
		return
	}
	if !a.memberLimit(w, r, "upload:"+u.ID, 120, 10*time.Minute) {
		return
	}
	id, token := newID(), randomToken()
	key := "uploads/" + id + ".raw"
	_, err := a.DB.Exec(r.Context(), `INSERT INTO media_files(id,owner_id,filename,mime_type,byte_size,storage_key,upload_token_hash,upload_expires_at,upload_audience) VALUES($1,$2,$3,$4,$5,$6,$7,now()+interval '15 minutes',$8)`, id, u.ID, input.Filename, input.MIME, input.Size, key, tokenHash(token), a.surface())
	if err != nil {
		memberDBError(w, err)
		return
	}
	writeJSON(w, 201, map[string]any{"data": map[string]any{"media_id": id, "upload_url": "/api/v1/uploads/" + id + "/content?token=" + token, "method": "PUT", "headers": map[string]string{"Content-Type": input.MIME}, "expires_in": 900}})
}

// Storage keys are generated by this service (or the trusted import CLI).
func mediaPath(root, key string) (string, error) {
	if key == "" || strings.ContainsAny(key, "\\:\x00") || strings.HasPrefix(key, "/") {
		return "", errors.New("invalid storage key")
	}
	clean := filepath.Clean(filepath.FromSlash(key))
	if clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", errors.New("invalid storage key")
	}
	base, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	target := filepath.Join(base, clean)
	rel, err := filepath.Rel(base, target)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.New("invalid storage path")
	}
	return target, nil
}
func readMediaPath(root, key string) (string, error) {
	target, err := mediaPath(root, key)
	if err != nil {
		return "", err
	}
	real, err := filepath.EvalSymlinks(target)
	if err != nil {
		return "", err
	}
	base, err := filepath.EvalSymlinks(root)
	if err != nil {
		return "", err
	}
	base, err = filepath.Abs(base)
	if err != nil {
		return "", err
	}
	real, err = filepath.Abs(real)
	if err != nil {
		return "", err
	}
	rel, err := filepath.Rel(base, real)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.New("storage symlink escapes root")
	}
	return real, nil
}
func (a *App) receiveUpload(w http.ResponseWriter, r *http.Request) {
	token := r.URL.Query().Get("token")
	if len(token) != 64 {
		fail(w, 403, "UPLOAD_TOKEN_INVALID", "上传凭据无效或过期")
		return
	}
	var hash, key, state string
	var size int64
	var expires time.Time
	err := a.DB.QueryRow(r.Context(), `SELECT COALESCE(upload_token_hash,''),storage_key,status,byte_size,COALESCE(upload_expires_at,created_at) FROM media_files WHERE id=$1 AND upload_audience=$2`, r.PathValue("id"), a.surface()).Scan(&hash, &key, &state, &size, &expires)
	if err != nil || subtle.ConstantTimeCompare([]byte(hash), []byte(tokenHash(token))) != 1 || time.Now().After(expires) {
		fail(w, 403, "UPLOAD_TOKEN_INVALID", "上传凭据无效或过期")
		return
	}
	// Lost transport responses can be retried, but a consumed ticket cannot overwrite its file.
	if state == "uploaded" || state == "ready" {
		writeJSON(w, 200, map[string]any{"data": map[string]any{"ok": true}})
		return
	}
	if state != "pending" {
		fail(w, 409, "UPLOAD_CLOSED", "此上传已关闭")
		return
	}
	if size > a.uploadMax() || size < 1 {
		fail(w, 413, "IMAGE_TOO_LARGE", "单张图片大小超过限制")
		return
	}
	if r.ContentLength >= 0 && r.ContentLength != size {
		fail(w, 422, "UPLOAD_SIZE_MISMATCH", "图片大小与上传申请不一致")
		return
	}
	path, err := mediaPath(a.Config.MediaDir, key)
	if err != nil {
		fail(w, 500, "STORAGE_ERROR", "图片存储不可用")
		return
	}
	if err = os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		fail(w, 503, "STORAGE_ERROR", "图片存储不可用")
		return
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".incoming-*")
	if err != nil {
		fail(w, 503, "STORAGE_ERROR", "图片存储不可用")
		return
	}
	temp := f.Name()
	defer os.Remove(temp)
	r.Body = http.MaxBytesReader(w, r.Body, size)
	n, copyErr := io.Copy(f, r.Body)
	closeErr := f.Close()
	if copyErr != nil || closeErr != nil || n != size {
		fail(w, 422, "UPLOAD_SIZE_MISMATCH", "图片上传不完整或大小不一致")
		return
	}
	// The potentially slow HTTP transfer holds no database connection. The short
	// commit transaction rechecks the ticket, so concurrent retries cannot replace
	// a file that has already been accepted or sanitized.
	tx, err := a.DB.Begin(r.Context())
	if err != nil {
		memberDBError(w, err)
		return
	}
	defer tx.Rollback(r.Context())
	var currentKey string
	var currentSize int64
	err = tx.QueryRow(r.Context(), `SELECT COALESCE(upload_token_hash,''),storage_key,status,byte_size,COALESCE(upload_expires_at,created_at) FROM media_files WHERE id=$1 AND upload_audience=$2 FOR UPDATE`, r.PathValue("id"), a.surface()).Scan(&hash, &currentKey, &state, &currentSize, &expires)
	if err != nil || subtle.ConstantTimeCompare([]byte(hash), []byte(tokenHash(token))) != 1 || time.Now().After(expires) {
		fail(w, 403, "UPLOAD_TOKEN_INVALID", "上传凭据无效或过期")
		return
	}
	if state == "uploaded" {
		writeJSON(w, 200, map[string]any{"data": map[string]any{"ok": true}})
		return
	}
	if state != "pending" || currentKey != key || currentSize != size {
		fail(w, 409, "UPLOAD_CLOSED", "此上传已关闭或发生变化")
		return
	}
	if err = os.Rename(temp, path); err != nil {
		fail(w, 503, "STORAGE_ERROR", "保存图片失败")
		return
	}
	_, err = tx.Exec(r.Context(), `UPDATE media_files SET status='uploaded' WHERE id=$1`, r.PathValue("id"))
	if err == nil {
		err = tx.Commit(r.Context())
	}
	if err != nil {
		memberDBError(w, err)
		return
	}
	writeJSON(w, 200, map[string]any{"data": map[string]any{"ok": true}})
}

// reencodeImage validates actual bytes, bounds decompression and strips metadata.
func reencodeImage(source io.ReadSeeker, dest io.Writer, expectedMIME string) (string, error) {
	cfg, format, err := image.DecodeConfig(source)
	if err != nil {
		return "", errors.New("图片无法解码")
	}
	mime := map[string]string{"jpeg": "image/jpeg", "png": "image/png", "webp": "image/webp"}[format]
	if mime == "" || mime != expectedMIME {
		return "", errors.New("图片实际格式与声明不一致")
	}
	if cfg.Width < 1 || cfg.Height < 1 || cfg.Width > 16000 || cfg.Height > 16000 || int64(cfg.Width)*int64(cfg.Height) > maxImagePixels {
		return "", errors.New("图片像素过大，请缩小后上传")
	}
	if _, err = source.Seek(0, io.SeekStart); err != nil {
		return "", err
	}
	decoded, _, err := image.Decode(source)
	if err != nil {
		return "", errors.New("图片内容损坏")
	}
	if format == "jpeg" {
		err = jpeg.Encode(dest, decoded, &jpeg.Options{Quality: 90})
		return "image/jpeg", err
	}
	err = png.Encode(dest, decoded)
	return "image/png", err
}

type limitedImageWriter struct {
	w         io.Writer
	remaining int64
}

func (w *limitedImageWriter) Write(p []byte) (int, error) {
	if int64(len(p)) > w.remaining {
		return 0, errors.New("处理后的图片过大")
	}
	n, e := w.w.Write(p)
	w.remaining -= int64(n)
	return n, e
}
func (a *App) completeUpload(w http.ResponseWriter, r *http.Request) {
	u, ok := a.requireUser(w, r)
	if !ok {
		return
	}
	timer := time.NewTimer(15 * time.Second)
	defer timer.Stop()
	select {
	case imageProcessors <- struct{}{}:
		defer func() { <-imageProcessors }()
	case <-r.Context().Done():
		return
	case <-timer.C:
		fail(w, 429, "IMAGE_PROCESSOR_BUSY", "图片处理繁忙，请稍后重试")
		return
	}
	tx, err := a.DB.Begin(r.Context())
	if err != nil {
		memberDBError(w, err)
		return
	}
	defer tx.Rollback(r.Context())
	id := r.PathValue("id")
	var key, mime, state string
	err = tx.QueryRow(r.Context(), `SELECT storage_key,mime_type,status FROM media_files WHERE id=$1 AND owner_id=$2 AND upload_audience=$3 FOR UPDATE`, id, u.ID, a.surface()).Scan(&key, &mime, &state)
	if err != nil {
		memberDBError(w, err)
		return
	}
	result := func() {
		writeJSON(w, 200, map[string]any{"data": map[string]any{"id": id, "status": "ready", "url": "/api/v1/media/" + id + "/file", "preview_url": "/api/v1/media/" + id + "/preview"}})
	}
	if state == "ready" {
		result()
		return
	}
	if state != "uploaded" {
		fail(w, 422, "MEDIA_NOT_UPLOADED", "图片尚未上传或未通过校验")
		return
	}
	sourcePath, err := readMediaPath(a.Config.MediaDir, key)
	if err != nil {
		fail(w, 503, "STORAGE_ERROR", "找不到已上传的图片，请重新上传")
		return
	}
	src, err := os.Open(sourcePath)
	if err != nil {
		fail(w, 503, "STORAGE_ERROR", "读取图片失败")
		return
	}
	defer src.Close()
	outputKey := "images/" + id + ".png"
	if mime == "image/jpeg" {
		outputKey = "images/" + id + ".jpg"
	}
	outputPath, err := mediaPath(a.Config.MediaDir, outputKey)
	if err != nil {
		fail(w, 500, "STORAGE_ERROR", "存储路径无效")
		return
	}
	if err = os.MkdirAll(filepath.Dir(outputPath), 0700); err != nil {
		fail(w, 503, "STORAGE_ERROR", "图片存储不可用")
		return
	}
	dst, err := os.CreateTemp(filepath.Dir(outputPath), ".processed-*")
	if err != nil {
		fail(w, 503, "STORAGE_ERROR", "图片存储不可用")
		return
	}
	temp := dst.Name()
	defer os.Remove(temp)
	outputMIME, processErr := reencodeImage(src, &limitedImageWriter{w: dst, remaining: 64 << 20}, mime)
	closeErr := dst.Close()
	if processErr != nil {
		_, _ = tx.Exec(r.Context(), `UPDATE media_files SET status='failed',upload_token_hash=NULL WHERE id=$1`, id)
		_ = tx.Commit(r.Context())
		_ = src.Close()
		_ = os.Remove(sourcePath)
		fail(w, 422, "INVALID_IMAGE", processErr.Error())
		return
	}
	if closeErr != nil {
		fail(w, 503, "STORAGE_ERROR", "保存处理图片失败")
		return
	}
	info, err := os.Stat(temp)
	if err != nil {
		fail(w, 503, "STORAGE_ERROR", "读取处理图片失败")
		return
	}
	if err = os.Rename(temp, outputPath); err != nil {
		fail(w, 503, "STORAGE_ERROR", "保存处理图片失败")
		return
	}
	_, err = tx.Exec(r.Context(), `UPDATE media_files SET storage_key=$1,mime_type=$2,byte_size=$3,status='ready',upload_token_hash=NULL WHERE id=$4`, outputKey, outputMIME, info.Size(), id)
	if err == nil {
		err = tx.Commit(r.Context())
	}
	if err != nil {
		memberDBError(w, err)
		return
	}
	// Raw originals may contain location metadata; retain only sanitized member uploads.
	_ = src.Close()
	_ = os.Remove(sourcePath)
	result()
}
func (a *App) serveMedia(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	var owner, key, mime, state string
	var public bool
	err := a.DB.QueryRow(r.Context(), `SELECT COALESCE(m.owner_id,''),m.storage_key,m.mime_type,m.status,
 EXISTS(SELECT 1 FROM product_images pi JOIN products p ON p.id=pi.product_id JOIN categories c ON c.id=p.category_id WHERE pi.media_id=m.id AND p.status='published' AND p.approved_version=p.version AND c.enabled)
 OR EXISTS(SELECT 1 FROM contacts c WHERE c.qr_media_id=m.id AND c.enabled)
 FROM media_files m WHERE m.id=$1`, id).Scan(&owner, &key, &mime, &state, &public)
	if err != nil {
		memberDBError(w, err)
		return
	}
	if state != "ready" {
		fail(w, 404, "MEDIA_NOT_READY", "图片暂不可用")
		return
	}
	if !public {
		u, err := a.currentUser(r)
		if err != nil {
			fail(w, 404, "NOT_FOUND", "图片不存在或尚未公开")
			return
		}
		permitted := u.Role == "admin" || u.ID == owner
		if !permitted {
			err = a.DB.QueryRow(r.Context(), `SELECT EXISTS(SELECT 1 FROM product_images pi JOIN products p ON p.id=pi.product_id WHERE pi.media_id=$1 AND p.owner_id=$2)`, id, u.ID).Scan(&permitted)
			if err != nil {
				memberDBError(w, err)
				return
			}
		}
		if !permitted {
			fail(w, 404, "NOT_FOUND", "图片不存在或尚未公开")
			return
		}
	}
	path, err := readMediaPath(a.Config.MediaDir, key)
	if err != nil {
		fail(w, 404, "MEDIA_FILE_MISSING", "图片暂不可用")
		return
	}
	if r.URL.Query().Get("variant") == "thumb" {
		if derived, ok := a.thumbnailPath(r.Context(), path, id); ok {
			path = derived
		}
	}
	f, err := os.Open(path)
	if err != nil {
		fail(w, 404, "MEDIA_FILE_MISSING", "图片暂不可用")
		return
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil || !info.Mode().IsRegular() {
		fail(w, 404, "MEDIA_FILE_MISSING", "图片暂不可用")
		return
	}
	// Imported media are local originals. Never fall back to a remote source URL.
	sample := make([]byte, 512)
	n, _ := f.Read(sample)
	detected := http.DetectContentType(sample[:n])
	_, _ = f.Seek(0, io.SeekStart)
	allowed := map[string]bool{"image/jpeg": true, "image/png": true, "image/webp": true, "image/gif": true, "image/avif": true}
	if !allowed[detected] {
		fail(w, 415, "INVALID_IMAGE_TYPE", "该媒体不是受支持的图片")
		return
	}
	mime = detected
	w.Header().Set("Content-Type", mime)
	w.Header().Set("X-Content-Type-Options", "nosniff")
	w.Header().Set("Cache-Control", "private, no-store")
	w.Header().Set("Content-Disposition", fmt.Sprintf("inline; filename=\"%s\"", id))
	http.ServeContent(w, r, id, info.ModTime(), f)
}
